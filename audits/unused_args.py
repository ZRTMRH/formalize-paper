#!/usr/bin/env python3
"""Arguments no proof uses, found by Batteries' `unusedArguments` linter (Phase 0, review only).

WHY THIS EXISTS.  In a test run an idle `[NeZero k]` was reported by the substantiveness
lane in every round, by hand, one declaration at a time; and the lanes' own evidence for "this
hypothesis is needed" was a deletion test that shows a hypothesis is *named*, not that it is
*used*. The linter answers the real question for the whole library in one pass: which arguments
does no proof term mention? It is a SCREEN, not the whole check: an argument the statement itself
mentions (an instance `[NeZero k]` needed to elaborate `(0 : Fin k)`) counts as used even if the
proof never needs it, so the lanes' removal probe stays for that case.

  python3 audits/unused_args.py [--project NAME] [--write]   # run the linter (needs a built project)
  python3 audits/unused_args.py --selftest                     # the parser, on fixed linter output

`--write` puts the list in `<ROUNDS-DIR>/UNUSED_ARGS.md`, split into
  - approved statements (their hypotheses may mirror the paper's: an idle one is a fact to report
    about the paper or the statement, not something to delete), and
  - everything else (helpers): each is a finding for the adjudicator -- drop the argument, or say
    why it must stay.
Exit 0 always (review); exit 2 if the linter could not run.
"""
import sys
sys.dont_write_bytecode = True
import argparse, json, os, re, subprocess, tempfile

import project

# `#check @name` when the declaration has implicit arguments, `#check name` otherwise
CHECK_RE = re.compile(r"^#check @?(\S+) /- (\d+) unused arguments?:\s*$")
ARG_RE = re.compile(r"^\s+argument (\d+): (.*?)(?: -/)?$")


def parse(out):
    """[(declaration, [argument text])] from `#lint only unusedArguments` output."""
    res, cur = [], None
    for line in out.splitlines():
        if line.startswith("#check"):
            m = CHECK_RE.match(line.strip())
            cur = (m.group(1), []) if m else None       # an unparsed entry must not absorb lines
            if cur:
                res.append(cur)
            continue
        a = ARG_RE.match(line)
        if a and cur is not None:
            cur[1].append(f"argument {a.group(1)}: {a.group(2).strip()}")
    return res


def approved_names(cfg):
    p = os.path.join(project.REPO, cfg["rounds_dir"], "APPROVED_FINGERPRINTS.json")
    if not os.path.exists(p):
        return set()
    a = json.load(open(p, encoding="utf-8"))
    return set(a.get("fingerprints", {}))


def run_linter(cfg):
    module = cfg.get("sweep", {}).get("module") or cfg["namespace"]
    d = tempfile.mkdtemp(prefix="unused-args-")
    f = os.path.join(d, "Lint.lean")
    open(f, "w").write(f"import {module}\n#lint only unusedArguments in {cfg['namespace']}\n")
    r = subprocess.run(["lake", "env", "lean", f], cwd=project.REPO, capture_output=True, text=True)
    out = r.stdout + r.stderr
    if "unusedArguments" not in out and "Found 0 errors" not in out and "linting passed" not in out.lower():
        return None, out
    return parse(out), out


def render(found, approved):
    stmt = [(n, a) for n, a in found if n in approved]
    helper = [(n, a) for n, a in found if n not in approved]
    lines = ["# Unused arguments (Batteries `unusedArguments` linter; generated by audits/unused_args.py)", "",
             "Arguments that no proof term mentions. Regenerated by Phase 0; do not edit.", "",
             f"## Helpers ({len(helper)}): each is a finding -- drop the argument, or record why it must stay", ""]
    lines += [f"- `{n}`: " + "; ".join(a) for n, a in helper] or ["(none)"]
    lines += ["", f"## Approved statements ({len(stmt)}): hypotheses that may mirror the paper's; report, do not delete", ""]
    lines += [f"- `{n}`: " + "; ".join(a) for n, a in stmt] or ["(none)"]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--project")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    try:
        cfg, _ = project.select(a.project)
    except project.SelectionError as e:
        print(f"FAIL: {e}", file=sys.stderr); return 2
    dest = os.path.join(project.REPO, cfg["rounds_dir"], "UNUSED_ARGS.md")
    head = subprocess.run(["git", "-C", project.REPO, "rev-parse", "--short=11", "HEAD"],
                          capture_output=True, text=True).stdout.strip() or "unknown"
    found, out = run_linter(cfg)
    if found is None:
        print("the linter did not run (is the project built?):\n" + out[-1500:])
        if a.write:     # never leave an older list in place: it would read as current
            open(dest, "w", encoding="utf-8").write(f"# Unused arguments: NOT RUN at commit {head}\n\n"
                                                    "The linter did not run; there is no current list.\n")
        return 2
    approved = approved_names(cfg)
    names = {n for n, _ in found}
    text = render(found, approved).replace("Regenerated by Phase 0; do not edit.",
                                            f"Generated at commit {head}. Regenerated by Phase 0; do not edit.")
    print(text)
    print(f"(approved set: {len(approved)} names; the linter reported {len(names & approved)} of them)")
    if a.write:
        open(dest, "w", encoding="utf-8").write(text)
    return 0


SAMPLE = """L.lean:2:0: error: -- Found 2 errors in 750 declarations
/- The `unusedArguments` linter reports:
UNUSED ARGUMENTS. -/
-- Ns.Section1
#check @Ns.lemma_1_4 /- 2 unused arguments:
  argument 6: (hP : Ns.IsPattern P)
  argument 7: (hlines : Ns.NoEmptyLines P) -/
#check @Ns.helper_x /- 1 unused argument:
  argument 3: [inst : NeZero k] -/
#check Ns.no_implicits /- 1 unused argument:
  argument 2: [inst : NeZero k] -/
"""


def selftest():
    res = []
    def say(n, ok):
        res.append(ok); print(f"  {'ok  ' if ok else 'FAIL'}  {n}")
    f = parse(SAMPLE)
    say("the linter's output is parsed into declarations and arguments",
        f == [("Ns.lemma_1_4", ["argument 6: (hP : Ns.IsPattern P)", "argument 7: (hlines : Ns.NoEmptyLines P)"]),
              ("Ns.helper_x", ["argument 3: [inst : NeZero k]"]),
              ("Ns.no_implicits", ["argument 2: [inst : NeZero k]"])])
    t = render(f, {"Ns.lemma_1_4"})
    say("approved statements and helpers are listed apart",
        "## Helpers (2)" in t and "`Ns.helper_x`" in t.split("## Approved")[0]
        and "`Ns.lemma_1_4`" in t.split("## Approved")[1])
    say("an empty result says so", "(none)" in render([], set()))
    print("selftest:", "ok" if all(res) else "FAILED")
    return 0 if all(res) else 1


if __name__ == "__main__":
    sys.exit(main())
