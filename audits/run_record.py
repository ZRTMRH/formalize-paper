def _tool_patch():
    """The tool_patch module, or None (an installation without it, or one that cannot be imported)."""
    try:
        import tool_patch
        return tool_patch
    except Exception:       # noqa: BLE001 -- no tool-patch route here: no section text beyond "none"
        return None


def tool_patch_lines(cfg):
    tp = _tool_patch()
    if tp is None or not hasattr(tp, "record_lines"):
        return []
    ls = list(tp.record_lines(cfg) or [])
    # tool_patch.record_lines opens with its own "## Tool patches" heading: RUN_RECORD.md numbers its sections, so
    # the section heading is ours (integrity.run_record_problems reads the section by its numbered heading)
    while ls and (not ls[0].strip() or ls[0].startswith("## ")):
        ls.pop(0)
    return ls


def applied_patches(cfg):
    """[(tp_id, patch_sha256, review_seal_commit, apply_commit)] of every applied tool patch ([] without the
    module)."""
    tp = _tool_patch()
    if tp is None or not hasattr(tp, "applied"):
        return []
    return [tuple(x) for x in tp.applied(cfg) or []]


def _cell(c):
    return str(c).replace("|", "\\|").replace("\n", " ")


def _table(header, rows):
    return ("| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
            + "".join("| " + " | ".join(_cell(c) for c in (list(r) + [""] * len(header))[:len(header)]) + " |\n"
                      for r in rows))


def _log(cfg):
    p = os.path.join(project.REPO, cfg["rounds_dir"], "RUN_LOG.md")
    try:
        return open(p, encoding="utf-8").read()
    except OSError:
        return ""


def pre_delivery_notices(cfg):
    """[path] of the known-fault notices the generator may read (project.GEN_INPUTS: the approved sheet's and the
    Checkpoint B questions' readers), of the approved round."""
    rd = os.path.join(project.REPO, cfg["rounds_dir"])
    ar = project.approved_round(cfg)
    if not ar:
        return []
    return [p for p in (os.path.join(rd, f"KNOWN_FAULTS-signoff-{ar}.md"), os.path.join(rd, f"KNOWN_FAULTS-questions-{ar}.md"))
            if os.path.isfile(p) and not os.path.islink(p)]


def _notice_block(path):
    body = open(path, encoding="utf-8", errors="replace").read().strip()
    body = re.sub(r"(?m)^(#+) ", lambda m: "#" * min(6, len(m.group(1)) + 3) + " ", body)
    return f"### `{os.path.basename(path)}`\n\n{body}\n"


def text(cfg):
    """RUN_RECORD.md as the generator writes it now."""
    import make_report as mr, stops, decisions
    rd = os.path.join(project.REPO, cfg["rounds_dir"])
    out = [f"# Run record — {cfg.get('source_cite', cfg.get('name', '?'))}", "", INTRO, "",
           f"Project `{cfg.get('name', '?')}`; Lean commit `{project.delivered_commit(cfg)}`; run mode "
           f"{project.mode(cfg)}; involvement {project.involvement(cfg)}.", ""]
    # 1. tool patches (the OPERATOR-PATCH route): its own lines, or none
    tl = tool_patch_lines(cfg)
    out += [f"## 1. {TOOL_PATCH_TITLE}", ""] + (tl if tl else [TOOL_PATCH_NONE]) + [""]
    # 2. every stop, then those cleared without the human
    srows = mr.all_stops(cfg)
    out += [f"## 2. {STOPS_TITLE}", "", mr.ALL_STOPS_INTRO, ""]
    out += [_table(["stop", "date", "the stop", "cause class", "decided by", "outcome"], srows) if srows else NONE, ""]
    res = mr.resolved_stops(cfg)
    out += [f"## 3. {CLEARED_TITLE}", "",
            mr.RESOLVED_INTRO + (mr.RESOLVED_WITHDRAWN if any(r[5] == "withdrawn" for r in res) else ""), ""]
    out += [_table(["stop", "date", "the stop", "cause class", "what was done", "outcome"], res) if res
            else mr.NO_RESOLVED, ""]
    # C2-FIX 5b review 2: every request to close a stop as not verified, with its reviewer's verdict (a rejection too)
    try:
        crl = stops.core_request_lines(cfg)
    except Exception as e:      # noqa: BLE001 -- said, never hidden
        crl = [f"- the core-fault requests could not be read: {e!r}"]
    if crl:
        out += ["Requests to close a stop as not verified (a fault of a proof-validity check; stops.py core-fault), "
                "each with its fresh reviewer's verdict:", ""] + crl + [""]
    # 4. set-asides and clearances
    sa, cl = mr.set_asides(cfg), mr.clearances_shown(cfg)
    out += [f"## 4. {SET_ASIDE_TITLE}", "", mr.SET_ASIDE_INTRO, ""]
    if sa:
        out += [_table(["set aside", "date", "decided by", "inventory", "reason"], sa)]
    if cl:
        out += [_table(["round", "cleared lane", "reason"], cl)]
    if not sa and not cl:
        out += [mr.NO_SETASIDE]
    out += [""]
    # SWEEP-FIX D1: each grace round of a statement-round cap (signoff.py approve refused the last round for a
    # mechanical reason; scope.grace_record), listed when there is one
    import scope
    gr = scope.grace_rows(cfg)
    if gr:
        out += ["Statement-round cap: grace rounds (the last round at the cap was refused for a mechanical reason, "
                "so one more statement round was allowed and not counted):", ""]
        out += [f"- after round {r}: {project.full(why)}" for r, why in gr] + [""]
    # 5. the apparatus: re-pins, reissues
    reps = []
    try:
        reps = json.load(open(os.path.join(rd, "TOOLING_PIN.json"), encoding="utf-8")).get("repins", []) or []
    except (OSError, ValueError, AttributeError):
        pass
    out += [f"## 5. {APPARATUS_TITLE}", "",
            "The scripts, prompts and reviewer definition were frozen for the run (`integrity.py --check`). Each "
            "re-pin (a new frozen version, with its stated reason) and each reissued lane:", ""]
    out += ([f"- re-pin {i}: {r.get('date', '?')}: {project.full(r.get('reason') or r.get('tool_patch') or '?')}"
             for i, r in enumerate(reps, 1)] or ["- re-pins: none (unchanged since the pin)"])
    try:
        _l, _w, rs = mr.reissue_row(cfg)
    except Exception as e:      # noqa: BLE001 -- said, never hidden
        rs = f"the reissue record could not be read ({type(e).__name__}: {e})"
    out += [f"- lane reissues: {rs}"] + comment_only_lines(cfg) + [""]
    # 6. disclosed faults (release mode)
    drows = stops.disclosed_rows(cfg, phase="run")
    out += [f"## 6. {DISCLOSED_TITLE}", "",
            "Release mode: a fault of presentation or bookkeeping, or of a tool that serves only those, is disclosed "
            "instead of stopping the run (`stops.py disclose`; record: `stops/disclosed/`).", ""]
    out += ([f"- {r['fault']} ({r.get('date') or '?'}; {', '.join(r['codes'])}): {project.full(r['what'])}" for r in drows]
            or [NONE]) + [""]
    # 7. mechanical failures (the operator's log)
    mech = decisions.section(_log(cfg), "Mechanical failures").strip()
    out += [f"## 7. {MECHANICAL_TITLE}", "", "As logged in `RUN_LOG.md`, \"Mechanical failures\":", "",
            mech if mech else NONE, ""]
    # 8. the pre-delivery readers' known-fault notices (folded in)
    ns = pre_delivery_notices(cfg)
    out += [f"## 8. {NOTICES_TITLE}", "",
            "Findings of a fresh reader that the operator answered as unfixable, folded in from their notices "
            "(`KNOWN_FAULTS-<document>-<n>.md`; not delivered separately). The notices of the delivered summary, "
            "report and decisions document are added at delivery, below.", ""]
    out += ([_notice_block(p) for p in ns] or [NONE]) + [""]
    # 9. history faults acknowledged after a fresh review (SWEEP-FIX D2; integrity.py --ack-request)
    out += [f"## 9. {ACK_TITLE}", "", ACK_INTRO, ""] + (ack_lines(cfg) or [NONE]) + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def comment_only_lines(cfg, c=None):
    """DESIGN-M7: the section-5 bullet when the Lean changes after the last audit round were accepted as comment-only
    on the source basis (the mechanism: which commits, and Lean's comparison with O1's field), else []. `c`: the
    changes_after_last_audit dict (default: computed); one that cannot be read adds nothing here (the report's row
    says what it can)."""
    try:
        c = project.changes_after_last_audit(cfg, project.rounds(cfg)) if c is None else c
    except Exception:       # noqa: BLE001 -- the report's "Changes after the last audit round" row is the disclosure
        return []
    if not c or c.get("problem") or not c.get("comment_only") or c.get("comment_only_basis") != "source":
        return []
    lean = "; ".join(project.full(str(w)) for w in c.get("comment_only_lean") or []) or "(none recorded)"
    return [f"- comment-only check: commit(s) {'; '.join(c.get('commits') or [])} accepted as comment-only on the "
            "source text (DESIGN-M7): the code with comments and docstrings removed is identical; Lean's comparison: "
            + lean]


def ack_lines(cfg):
    """[markdown line] of every reviewed acknowledgment request of the run (integrity.acknowledgments)."""
    import integrity
    rd = os.path.join(project.REPO, cfg["rounds_dir"])
    out = []
    for a in integrity.acknowledgments(project.AUDITS, rd):
        state = ("acknowledged" if a["valid"] else f"NOT acknowledged ({a['why']})")
        out += [f"### {a['ak']} ({a.get('date') or '?'}): {state}", "",
                f"- the operator's diagnosis: {project.full(a['diagnosis'])}",
                f"- the reviewer ({a.get('reviewer') or 'none sealed'}): {a.get('verdict') or 'no verdict'}"
                + (f": {project.full(a['reason'])}" if a.get("reason") else ""),
                "- the lines (`integrity.py --check` prints each as NOTE[acknowledged-fault] while it is acknowledged):"]
        out += [f"  - `{l}`" for l in a["lines"]] + [""]
    return out


NOTES_AT_DELIVERY = "Notes at delivery"


def notes_lines(notes, judged=None):
    """The `### Notes at delivery` part `--deliver` appends to the delivered run record (DESIGN-E fix 2): every note
    of the delivery checks, deduplicated in order, word for word (the README's code-written section counts them by
    kind and points here), each with its id and who judged it (DESIGN-SW2 1.14: `judged` = project.note_judgements;
    absent: nobody)."""
    ns = list(dict.fromkeys(" ".join(str(n).split()) for n in notes or []))
    out = ["", f"### {NOTES_AT_DELIVERY}", "",
           "Written by `project.py --deliver`: every note its checks printed for the formalizing agent, word for word "
           "(a note never stops a delivery), with its id and who judged it (the NOTES reviewer's "
           "`delivery-review/NOTES.md`, committed under the subject \"delivery review\" and saved by the formalizing "
           "agent, so the record cannot show who wrote it; the "
           "operator's `## Delivery notes` in JUDGEMENT.md, or nobody)."]
    j = judged or {}
    out += [""] + [f"- [{project.note_id(n)}] {n} -- judged: {project.judged_word(j.get(project.note_id(n)))}"
                   for n in ns] if ns else ["", NONE]
    return "\n".join(out) + "\n"


def delivery_section(cfg, kept, dropped):
    """The delivery-phase notes `--deliver` appends to the delivery copy only (ADDENDUM N6: what arose after the
    prepared documents): the known-fault notices of the delivered documents (`kept`, project.keep_notices: folded
    in, never delivered as files), the delivery-phase disclosures and stops, the superseded notices by name."""
    import stops
    out = ["", f"## {DELIVERY_TITLE}", "",
           "Written by `project.py --deliver` into this delivery copy only: what arose after the documents were "
           "prepared."]
    # C1 audit / approver 2026-10-25: the delivery's own times, recorded by the code (RUN_LOG.md "## Delivery" too)
    import datetime
    if getattr(project, "DELIVERY_STARTED", None):
        out += ["", f"Delivery: `project.py --deliver` started {project.DELIVERY_STARTED}; this run record was written "
                    f"{datetime.datetime.now().astimezone().strftime('%Y-%m-%d %H:%M:%S %z')}, at the end of its "
                    f"checks. Every attempt, with its start, end and outcome, is in `RUN_LOG.md`, \"## Delivery\"."]
    pre = {os.path.basename(p) for p in pre_delivery_notices(cfg)}
    later = [p for p in kept if os.path.basename(p) not in pre and os.path.isfile(p)]
    if later:
        out += ["", "Known-fault notices of the delivered documents (folded in):", ""] + [_notice_block(p) for p in later]
    drows, srows = stops.disclosed_rows(cfg, phase="delivery"), stops.stop_rows(cfg, phase="delivery")
    if drows or srows:
        out += ["", "Faults of the delivered documents themselves (disclosed, not in the documents: they arose "
                "after them):"] + [f"- {r['fault']} ({', '.join(r['codes'])}): {r['what']}" for r in drows] + [
                   f"- {r['stop']}: {r['what']}; {r['by']}; {r['done']}" for r in srows]
    if dropped:
        out += ["", "Notices of superseded documents (an earlier report or sheet), not delivered: "
                + ", ".join(f"`{os.path.basename(f)}`" for f in dropped) + ". A fault they name may still be in "
                "the delivered document if no later reader raised it again."]
    if not later and not drows and not srows and not dropped:
        out += ["", NONE]
    out += dismissed_lines(cfg)
    return "\n".join(out) + "\n"


DISMISSED_TITLE = "Reader findings dismissed"


def dismissed_lines(cfg):
    """DOC-FIX review #5: every finding of a fresh reader the operator dismissed (rejected), with the reason, as its
    committed response line says it (`- dismissed: <quote> — <reason>`), so the human sees each rejection; a
    reason can be any text, and nothing else in the delivery names them. Written by --deliver (the delivery copy)."""
    import readers
    rdir = readers.readers_dir(cfg)
    try:
        texts = readers.record_texts(rdir, use_git=True)
    except readers.DocError:
        texts = readers.record_texts(rdir, use_git=False)
    key = lambda s: [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", s)]
    rows = []
    for name in sorted((n for n in texts if re.search(r"\.response(?:-\d+)?\.md$", n)), key=key):
        got, _bad = readers.responses(texts, [name])
        rows += [f"- `readers/{name}`: {project.full(' '.join(body.split()))}"
                 for (kind, _c), body in zip(got, readers.responses.bodies) if kind == "dismissed"]
    return ["", f"### {DISMISSED_TITLE}", "",
            "Each finding of a fresh reader that the operator rejected (`dismissed`: not a real problem, with its "
            "evidence, or trivial), with the reason given, from the committed response files. Check any you doubt "
            "against the document."] + ([""] + rows if rows else ["", "None: no reader finding was dismissed."])


def _section(txt, title):
    m = re.search(rf"^## \d+\. {re.escape(title)}\s*$(.*?)(?=^## |\Z)", txt or "", re.M | re.S)
    return m.group(1) if m else ""


def listing_problems(cfg, txt=None):
    """[problem] when RUN_RECORD.md (`txt`, else the prepared file) does not name, by its generated line, every
    stop the operator closed (a release self-cure or a delegated close), every disclosed fault (run phase), every
    set-aside and every applied tool patch (its id, patch sha256, review seal and apply commit). The F2 completeness
    check of the process record (it replaced REPORT's and DECISIONS' stop and disclosure coverage)."""
    import stops
    if txt is None:
        try:
            txt = open(os.path.join(project.REPO, cfg["rounds_dir"], RUN_RECORD_MD), encoding="utf-8").read()
        except OSError:
            return [f"{RUN_RECORD_MD} is missing: python3 audits/project.py --prepare-delivery"]
    out = []
    st_, cl_, sa_, ds_, tp_ = (_section(txt, t) for t in (STOPS_TITLE, CLEARED_TITLE, SET_ASIDE_TITLE,
                                                          DISCLOSED_TITLE, TOOL_PATCH_TITLE))
    for r in stops.stop_rows(cfg, phase="run"):
        if not re.search(rf"(?m)^\| {re.escape(r['stop'])} \|", st_):
            out.append(f"{RUN_RECORD_MD} does not list stop {r['stop']} under \"{STOPS_TITLE}\"")
    for r in stops.disclosed_rows(cfg, phase="run"):
        for i in [r["id"]] + list(r.get("also") or []):
            if not re.search(rf"(?m)^- [^\n]*\b{re.escape(i)}\b", ds_):
                out.append(f"{RUN_RECORD_MD} does not name disclosed fault {i} under \"{DISCLOSED_TITLE}\"")
    # the mechanical provenance check (integrity.py, read from the raw records: re-pins, apply commits, CLOSED.json,
    # set-aside markers) -- the one the root of trust runs as `integrity.py --check-run-record`
    import integrity
    out += integrity.run_record_problems(project.AUDITS, os.path.join(project.REPO, cfg["rounds_dir"]), txt)
    for tp_id, sha, seal, apply_ in applied_patches(cfg):
        seals = [x for x in str(seal or "").split(",") if x] or [""]
        for what, v in ((("id", tp_id), ("patch sha256", sha)) + tuple(("review seal", x) for x in seals)
                        + (("apply commit", apply_),)):
            if not v or str(v) not in tp_:
                out.append(f"{RUN_RECORD_MD} does not name tool patch {tp_id}'s {what} ({v}) under \"{TOOL_PATCH_TITLE}\"")
    return out


