def _tool_patch():
    """The tool_patch module, or None (an installation without it, or one that cannot be imported)."""
    try:
        import tool_patch
        return tool_patch
    except Exception:       # noqa: BLE001 -- no tool-patch route here: no section text beyond "none"
        return None


def tool_patch_lines(cfg):
    tp = _tool_patch()
    if tp is None or not hasattr(tp, "record_lines"):
        return []
    ls = list(tp.record_lines(cfg) or [])
    # tool_patch.record_lines opens with its own "## Tool patches" heading: RUN_RECORD.md numbers its sections, so
    # the section heading is ours (integrity.run_record_problems reads the section by its numbered heading)
    while ls and (not ls[0].strip() or ls[0].startswith("## ")):
        ls.pop(0)
    return ls


def applied_patches(cfg):
    """[(tp_id, patch_sha256, review_seal_commit, apply_commit)] of every applied tool patch ([] without the
    module)."""
    tp = _tool_patch()
    if tp is None or not hasattr(tp, "applied"):
        return []
    return [tuple(x) for x in tp.applied(cfg) or []]


def _cell(c):
    return str(c).replace("|", "\\|").replace("\n", " ")


def _table(header, rows):
    return ("| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
            + "".join("| " + " | ".join(_cell(c) for c in (list(r) + [""] * len(header))[:len(header)]) + " |\n"
                      for r in rows))


