def _notice_block(path):
    body = open(path, encoding="utf-8", errors="replace").read().strip()
    body = re.sub(r"(?m)^(#+) ", lambda m: "#" * min(6, len(m.group(1)) + 3) + " ", body)
    return f"### `{os.path.basename(path)}`\n\n{body}\n"


def text(cfg):
    """RUN_RECORD.md as the generator writes it now."""
    import make_report as mr, stops, decisions
    rd = os.path.join(project.REPO, cfg["rounds_dir"])
    out = [f"# Run record — {cfg.get('source_cite', cfg.get('name', '?'))}", "", INTRO, "",
           f"Project `{cfg.get('name', '?')}`; Lean commit `{project.delivered_commit(cfg)}`; run mode "
           f"{project.mode(cfg)}; involvement {project.involvement(cfg)}.", ""]
    # 1. tool patches (the OPERATOR-PATCH route): its own lines, or none
    tl = tool_patch_lines(cfg)
    out += [f"## 1. {TOOL_PATCH_TITLE}", ""] + (tl if tl else [TOOL_PATCH_NONE]) + [""]
    # 2. every stop, then those cleared without the human
    srows = mr.all_stops(cfg)
    out += [f"## 2. {STOPS_TITLE}", "", mr.ALL_STOPS_INTRO, ""]
    out += [_table(["stop", "date", "the stop", "cause class", "decided by", "outcome"], srows) if srows else NONE, ""]
    res = mr.resolved_stops(cfg)
    out += [f"## 3. {CLEARED_TITLE}", "", mr.RESOLVED_INTRO, ""]
    out += [_table(["stop", "date", "the stop", "cause class", "what was done", "outcome"], res) if res
            else mr.NO_RESOLVED, ""]
    # C2-FIX 5b review 2: every request to close a stop as not verified, with its reviewer's verdict (a rejection too)
    try:
        crl = stops.core_request_lines(cfg)
    except Exception as e:      # noqa: BLE001 -- said, never hidden
        crl = [f"- the core-fault requests could not be read: {e!r}"]
    if crl:
        out += ["Requests to close a stop as not verified (a fault of a proof-validity check; stops.py core-fault), "
                "each with its fresh reviewer's verdict:", ""] + crl + [""]
    # 4. set-asides and clearances
    sa, cl = mr.set_asides(cfg), mr.clearances_shown(cfg)
    out += [f"## 4. {SET_ASIDE_TITLE}", "", mr.SET_ASIDE_INTRO, ""]
    if sa:
        out += [_table(["set aside", "date", "decided by", "inventory", "reason"], sa)]
    if cl:
        out += [_table(["round", "cleared lane", "reason"], cl)]
    if not sa and not cl:
        out += [mr.NO_SETASIDE]
    out += [""]
    # SWEEP-FIX D1: each grace round of a statement-round cap (signoff.py approve refused the last round for a
    # mechanical reason; scope.grace_record), listed when there is one
    import scope
    gr = scope.grace_rows(cfg)
    if gr:
        out += ["Statement-round cap: grace rounds (the last round at the cap was refused for a mechanical reason, "
                "so one more statement round was allowed and not counted):", ""]
        out += [f"- after round {r}: {project.full(why)}" for r, why in gr] + [""]
    # 5. the apparatus: re-pins, reissues
    reps = []
    try:
        reps = json.load(open(os.path.join(rd, "TOOLING_PIN.json"), encoding="utf-8")).get("repins", []) or []
    except (OSError, ValueError, AttributeError):
        pass
    out += [f"## 5. {APPARATUS_TITLE}", "",
            "The scripts, prompts and reviewer definition were frozen for the run (`integrity.py --check`). Each "
            "re-pin (a new frozen version, with its stated reason) and each reissued lane:", ""]
    out += ([f"- re-pin {i}: {r.get('date', '?')}: {project.full(r.get('reason') or r.get('tool_patch') or '?')}"
             for i, r in enumerate(reps, 1)] or ["- re-pins: none (unchanged since the pin)"])
    try:
        _l, _w, rs = mr.reissue_row(cfg)
    except Exception as e:      # noqa: BLE001 -- said, never hidden
        rs = f"the reissue record could not be read ({type(e).__name__}: {e})"
    out += [f"- lane reissues: {rs}", ""]
    # 6. disclosed faults (release mode)
    drows = stops.disclosed_rows(cfg, phase="run")
    out += [f"## 6. {DISCLOSED_TITLE}", "",
            "Release mode: a fault of presentation or bookkeeping, or of a tool that serves only those, is disclosed "
            "instead of stopping the run (`stops.py disclose`; record: `stops/disclosed/`).", ""]
    out += ([f"- {r['fault']} ({r.get('date') or '?'}; {', '.join(r['codes'])}): {project.full(r['what'])}" for r in drows]
            or [NONE]) + [""]
    # 7. mechanical failures (the operator's log)
    mech = decisions.section(_log(cfg), "Mechanical failures").strip()
    out += [f"## 7. {MECHANICAL_TITLE}", "", "As logged in `RUN_LOG.md`, \"Mechanical failures\":", "",
            mech if mech else NONE, ""]
    # 8. the pre-delivery readers' known-fault notices (folded in)
    ns = pre_delivery_notices(cfg)
    out += [f"## 8. {NOTICES_TITLE}", "",
            "Findings of a fresh reader that the operator answered as unfixable, folded in from their notices "
            "(`KNOWN_FAULTS-<document>-<n>.md`; not delivered separately). The notices of the delivered summary, "
            "report and decisions document are added at delivery, below.", ""]
    out += ([_notice_block(p) for p in ns] or [NONE]) + [""]
    # 9. history faults acknowledged after a fresh review (SWEEP-FIX D2; integrity.py --ack-request)
    out += [f"## 9. {ACK_TITLE}", "", ACK_INTRO, ""] + (ack_lines(cfg) or [NONE]) + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def ack_lines(cfg):
    """[markdown line] of every reviewed acknowledgment request of the run (integrity.acknowledgments)."""
    import integrity
    rd = os.path.join(project.REPO, cfg["rounds_dir"])
    out = []
    for a in integrity.acknowledgments(project.AUDITS, rd):
        state = ("acknowledged" if a["valid"] else f"NOT acknowledged ({a['why']})")
        out += [f"### {a['ak']} ({a.get('date') or '?'}): {state}", "",
                f"- the operator's diagnosis: {project.full(a['diagnosis'])}",
                f"- the reviewer ({a.get('reviewer') or 'none sealed'}): {a.get('verdict') or 'no verdict'}"
                + (f": {project.full(a['reason'])}" if a.get("reason") else ""),
                "- the lines (`integrity.py --check` prints each as NOTE[acknowledged-fault] while it is acknowledged):"]
        out += [f"  - `{l}`" for l in a["lines"]] + [""]
    return out


def delivery_section(cfg, kept, dropped):
    """The delivery-phase notes `--deliver` appends to the delivery copy only (ADDENDUM N6: what arose after the
    prepared documents): the known-fault notices of the delivered documents (`kept`, project.keep_notices: folded
    in, never delivered as files), the delivery-phase disclosures and stops, the superseded notices by name."""
    import stops
    out = ["", f"## {DELIVERY_TITLE}", "",
           "Written by `project.py --deliver` into this delivery copy only: what arose after the documents were "
           "prepared."]
    # C1 audit / approver 2026-10-25: the delivery's own times, recorded by the code (RUN_LOG.md "## Delivery" too)
    import datetime
    if getattr(project, "DELIVERY_STARTED", None):
        out += ["", f"Delivery: `project.py --deliver` started {project.DELIVERY_STARTED}; this run record was written "
                    f"{datetime.datetime.now().astimezone().strftime('%Y-%m-%d %H:%M:%S %z')}, at the end of its "
                    f"checks. Every attempt, with its start, end and outcome, is in `RUN_LOG.md`, \"## Delivery\"."]
    pre = {os.path.basename(p) for p in pre_delivery_notices(cfg)}
    later = [p for p in kept if os.path.basename(p) not in pre and os.path.isfile(p)]
    if later:
        out += ["", "Known-fault notices of the delivered documents (folded in):", ""] + [_notice_block(p) for p in later]
    drows, srows = stops.disclosed_rows(cfg, phase="delivery"), stops.stop_rows(cfg, phase="delivery")
    if drows or srows:
        out += ["", "Faults of the delivered documents themselves (disclosed, not in the documents: they arose "
                "after them):"] + [f"- {r['fault']} ({', '.join(r['codes'])}): {r['what']}" for r in drows] + [
                   f"- {r['stop']}: {r['what']}; {r['by']}; {r['done']}" for r in srows]
    if dropped:
        out += ["", "Notices of superseded documents (an earlier report or sheet), not delivered: "
                + ", ".join(f"`{os.path.basename(f)}`" for f in dropped) + ". A fault they name may still be in "
                "the delivered document if no later reader raised it again."]
    if not later and not drows and not srows and not dropped:
        out += ["", NONE]
    out += hand_edit_lines(cfg)
    out += dismissed_lines(cfg)
    out += status_check_lines(cfg)
    return "\n".join(out) + "\n"


